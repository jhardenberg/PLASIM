def statements(text: str):
    """Join free-form continuation lines, ignoring Fortran comments/strings."""
    pending = ""
    for line in text.splitlines():
        # Preserve ! inside quoted strings while discarding actual comments.
        clean = re.match(r"(?:[^'\"!]|'(?:[^']|'')*'|\"(?:[^\"]|\"\")*\")*", line)[0]
        clean = clean.strip()
        if not clean:
            continue
        more = clean.endswith("&")
        pending += " " + clean.removeprefix("&").removesuffix("&").strip()
        if not more:
            yield pending.strip()
            pending = ""
    if pending:
        raise ValueError("Unterminated Fortran continuation")


def arguments(text: str) -> list[str]:
    """Split a Fortran argument list without splitting array subscripts."""
    result, start, depth = [], 0, 0
    for i, char in enumerate(text):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            result.append(text[start:i].strip())
            start = i + 1
    result.append(text[start:].strip())
    return result


def namelist_definitions():
    """Yield active groups and members from the reviewed implementations."""
    paths = [ROOT / "plasim/src" / f"{name}.f90" for name in SOURCES]
    paths.append(ROOT / "lsg/src/lsgmod.f90")
    for path in paths:
        found = []
        for statement in statements(path.read_text()):
            match = re.match(r"namelist\s*/\s*(\w+)\s*/(.*)", statement, re.I)
            if match:
                names = [n.strip().lower() for n in arguments(match[2])]
                if not all(re.fullmatch(r"[a-z]\w*", n) for n in names):
                    raise ValueError((path, statement))
                found.append((match[1].lower(), names))
        if not found:
            raise ValueError(f"No namelist found: {path}")
        relative = path.relative_to(ROOT).as_posix()
        for group, names in found:
            yield path, relative, group, names


def namelists() -> str:
    out = ["<!-- Generated by generate_reference.py; edit the generator or source. -->",
           "# Accepted namelist parameters", "",
           "This inventory is extracted from active Fortran `namelist` declarations.",
           "It includes the default rain/vegetation implementations, all three planet",
           "modules, the coupler, and LSG. An accepted name does not establish its",
           "effective default, units, availability in MoSt, or a valid combination.",
           "See {doc}`parameters/index` for detailed tables and {doc}`namelists` for",
           "the overview. Initialization code can override declarations;",
           "planet-specific lists must not be interchanged.", ""]
    for path, relative, group, names in namelist_definitions():
        out += [f"## `{group}` — `{path.name}`", "",
                f"Source: {{repo}}`{relative}` ({len(names)} names).", "",
                "```text", textwrap.fill(", ".join(names), width=76), "```", ""]
    return "\n".join(out)


def check_parameter_coverage() -> None:
    """Require a descriptive table row for each active member, without extras."""
    total = 0
    for path, _, group, names in namelist_definitions():
        page = DOC / "reference/parameters" / f"{PARAMETER_PAGES[path.stem]}.md"
        rows = re.findall(r"^\| `([a-z]\w*)` \|(.+)$", page.read_text(), re.M)
        documented = [name for name, _ in rows]
        missing = set(names) - set(documented)
        extra = set(documented) - set(names)
        duplicate = {name for name in documented if documented.count(name) > 1}
        incomplete = {name for name, cells in rows
                      if len(cells.split("|")) < 4 or any(
                          not cell.strip() for cell in cells.split("|")[:-1])}
        if missing or extra or duplicate or incomplete:
            raise SystemExit(
                f"Parameter coverage error in {page.relative_to(ROOT)} ({group}): "
                f"missing={sorted(missing)}, extra={sorted(extra)}, "
                f"duplicate={sorted(duplicate)}, incomplete={sorted(incomplete)}")
        total += len(names)
    print(f"Checked {total} parameter memberships across {len(PARAMETER_PAGES)} source groups")


def load_variable_metadata() -> dict[int, tuple[str, str, str]]:
    meta: dict[int, tuple[str, str, str]] = {}

    # 1. Parse variable_list.txt
    var_text = (ROOT / "plasim/doc/variable_list.txt").read_text()
    for line in var_text.splitlines():
        m = re.match(r"\|\s*(\S+)\s*\|\s*(.*?)\s*\|\s*([^|]*?)\s*\|\s*(\d+)\s*\|", line)
        if m:
            name, long_name, units, code = m.groups()
            meta[int(code)] = (name.strip(), long_name.strip(), units.strip())

    # 2. Supplement from srv2nc parameter tables
    srv_text = (ROOT / "scripts/srv2nc").read_text()
    for line in srv_text.splitlines():
        m = re.match(r"^\s*(\d+)\s+(\S+)\s+(.*?)\s+\[([^]]*)\]", line)
        if m:
            code_int = int(m.group(1))
            if code_int not in meta:
                meta[code_int] = (m.group(2).strip(), m.group(3).strip(), m.group(4).strip())

    # 3. Special cases: clear-sky fluxes, entropy, tendencies
    special = {
        91: ("dtdt1", "Temperature tendency term 1 (advection)", "K/s"),
        93: ("dtdt3", "Temperature tendency term 3 (diffusion)", "K/s"),
        94: ("dtdt4", "Temperature tendency term 4 (convection)", "K/s"),
        101: ("cl_dswfl_sfc", "Clear-sky surface downward solar flux", "W/m²"),
        102: ("cl_dlwfl_sfc", "Clear-sky surface downward thermal flux", "W/m²"),
        103: ("cl_dswfl_top", "Clear-sky top solar flux", "W/m²"),
        104: ("cl_dlwfl_top", "Clear-sky top thermal flux", "W/m²"),
        105: ("cl_dfu_top", "Clear-sky top upward solar flux", "W/m²"),
        106: ("cl_dfu_sfc", "Clear-sky surface upward solar flux", "W/m²"),
        107: ("cl_dftu_sfc", "Clear-sky surface upward thermal flux", "W/m²"),
        797: ("xentro", "Entropy production", "W/(m² K)"),
    }
    for code_int, val in special.items():
        if code_int not in meta or not meta[code_int][0]:
            meta[code_int] = val

    # Clean and standardize unit strings
    cleaned: dict[int, tuple[str, str, str]] = {}
    for code_int, (name, long_name, units) in meta.items():
        u = units.strip()
        u = u.replace("W/m2K", "W/(m² K)").replace("W/m2", "W/m²").replace("W/m**2", "W/m²")
        u = u.replace("mW/m2", "mW/m²")
        u = u.replace("m2/s2", "m²/s²").replace("m**2/s**2", "m²/s²")
        u = u.replace("m3/s3", "m³/s³").replace("m**3/s**3", "m³/s³")
        u = u.replace("m3/s", "m³/s")
        u = u.replace("m2/s", "m²/s").replace("m**2/s", "m²/s")
        u = u.replace("kg/m2", "kg/m²").replace("kg/m**2", "kg/m²")
        u = u.replace("0/00", "‰ (psu)")
        u = u.replace("0-1", "fraction [0, 1]").replace("frac.", "fraction [0, 1]")
        u = u.replace("m h2o", "m H₂O")
        if u in ("1", ""):
            u = "dimensionless"
        if u == "C":
            u = "°C"
        cleaned[code_int] = (name, long_name, u)

    return cleaned


