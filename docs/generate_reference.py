def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in inventories differ")
    args = parser.parse_args()
    check_parameter_coverage()
    outputs = {"namelist-inventory.md": namelists(), "raw-output.md": raw_output()}
    for name, text in outputs.items():
        path = DOC / "reference" / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Outdated {path.relative_to(ROOT)}; run python3 docs/generate_reference.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} source inventories")


if __name__ == "__main__":
    main()
