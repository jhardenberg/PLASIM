"""Generate documentation inventories from current code; --check detects drift.

This deliberately extracts names and literal output calls, not inferred physical
defaults. Initialization and runtime conditionals still require human review.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import textwrap

DOC = Path(__file__).resolve().parent
ROOT = DOC.parents[1]
SOURCES = [
    "plasim", "p_earth", "p_mars", "p_exo", "fluxmod", "miscmod",
    "surfmod", "landmod", "simba", "radmod", "rainmod", "seamod",
    "icemod", "oceanmod", "cpl",
]


def statements(text: str):
    """Join free-form continuation lines, ignoring Fortran comments/strings."""
    pending = ""
    for line in text.splitlines():
        # Preserve ! inside quoted strings while discarding actual comments.
        clean = re.match(r"(?:[^'\"!]|'(?:[^']|'')*'|\"(?:[^\"]|\"\")*\")*", line)[0]
        clean = clean.strip()
        if not clean:
            continue
        more = clean.endswith("&")
        pending += " " + clean.removeprefix("&").removesuffix("&").strip()
        if not more:
            yield pending.strip()
            pending = ""
    if pending:
        raise ValueError("Unterminated Fortran continuation")


def arguments(text: str) -> list[str]:
    """Split a Fortran argument list without splitting array subscripts."""
    result, start, depth = [], 0, 0
    for i, char in enumerate(text):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            result.append(text[start:i].strip())
            start = i + 1
    result.append(text[start:].strip())
    return result


def namelists() -> str:
    out = ["<!-- Generated by generate_reference.py; edit the generator or source. -->",
           "# Accepted namelist parameters", "",
           "This inventory is extracted from active Fortran `namelist` declarations.",
           "It includes the default rain/vegetation implementations, all three planet",
           "modules, the coupler, and LSG. An accepted name does not establish its",
           "effective default, units, availability in MoSt, or a valid combination.",
           "See {doc}`namelists` for usage and selected controls. Initialization code",
           "can override declarations; planet-specific lists must not be interchanged.", ""]
    paths = [ROOT / "plasim/src" / f"{name}.f90" for name in SOURCES]
    paths.append(ROOT / "lsg/src/lsgmod.f90")
    for path in paths:
        found = []
        for statement in statements(path.read_text()):
            match = re.match(r"namelist\s*/\s*(\w+)\s*/(.*)", statement, re.I)
            if match:
                names = [n.strip().lower() for n in arguments(match[2])]
                if not all(re.fullmatch(r"[a-z]\w*", n) for n in names):
                    raise ValueError((path, statement))
                found.append((match[1].lower(), names))
        if not found:
            raise ValueError(f"No namelist found: {path}")
        relative = path.relative_to(ROOT).as_posix()
        for group, names in found:
            out += [f"## `{group}` — `{path.name}`", "",
                    f"Source: {{repo}}`{relative}` ({len(names)} names).", "",
                    "```text", textwrap.fill(", ".join(names), width=76), "```", ""]
    return "\n".join(out)


def raw_output() -> str:
    out = ["<!-- Generated by generate_reference.py; edit the generator or source. -->",
           "# Raw output writer inventory", "",
           "Extracted from literal code assignments/calls in the current writers.",
           "Rows show code, source array, and the level argument. They do not imply",
           "that every field is enabled in every run. Dynamic diagnostic code ranges",
           "are described in {doc}`output`; code 333 is metadata, not a physical field.",
           "Compare with the separate {doc}`conversion-metadata` vocabulary when",
           "choosing a postprocessor; raw arrays and converted fields are distinct.", ""]
    for name, title in [("outmod", "Atmosphere"), ("icemod", "Sea ice"),
                        ("oceanmod", "Mixed-layer ocean")]:
        path = ROOT / f"plasim/src/{name}.f90"
        out += [f"## {title}", "", f"Source: {{repo}}`plasim/src/{name}.f90`.", "",
                "| Code | Source array/expression | Level argument | Writer |",
                "| --- | --- | --- | --- |"]
        code = None
        for statement in statements(path.read_text()):
            assign = re.match(r"ih\(1\)\s*=\s*(\d+)\s*$", statement, re.I)
            if assign:
                code = assign[1]
            elif re.match(r"ih\(1\)\s*=", statement, re.I):
                code = None
            call = re.match(r"call\s+(writegp|writesp|mpwritegph)\((.*)\)$", statement, re.I)
            if not call:
                continue
            args = arguments(call[2])
            writer = call[1].lower()
            if writer in ("writegp", "writesp") and args[2].isdigit():
                out.append(f"| {args[2]} | `{args[1]}` | `{args[3]}` | `{writer}` |")
            elif writer == "mpwritegph" and code:
                level = "ocean level index (jlev-1)" if name == "oceanmod" and code == "939" else "0"
                out.append(f"| {code} | `{args[1]}` | {level} | `{writer}` |")
        out.append("")
    return "\n".join(out)


def conversion_metadata() -> str:
    text = (ROOT / "scripts/srv2nc").read_text()
    out = ["<!-- Generated by generate_reference.py; edit the generator or source. -->",
           "# Conversion metadata vocabulary", "",
           "These are the names, labels, and unit strings declared by the current",
           "`srv2nc` conversion tables, extracted without changing them. This is a",
           "description of converter metadata, not a guarantee of raw-field units",
           "or field availability. Read {doc}`output` for representations, signs,",
           "averaging, and checks against model writers. Derived fields also appear",
           "here; the script's table does not itself compute all of them.", "",
           "Source: {repo}`scripts/srv2nc`.", ""]
    tables = re.findall(r"cat > (param(?:lsg)?).*?<< EOT\n(.*?)\nEOT", text, re.S)
    if len(tables) != 2:
        raise ValueError("Expected atmospheric/ice/ocean and LSG metadata tables")
    for name, table in tables:
        out += ["## LSG" if name == "paramlsg" else "## Atmosphere, ice, and mixed-layer ocean",
                "", "| Code | Converted name | Label | Declared units |",
                "| --- | --- | --- | --- |"]
        for line in table.splitlines():
            match = re.fullmatch(r"(\d+)\s+(\S+)\s+(.*?)\s+\[([^]]*)\]\s*", line)
            if not match:
                raise ValueError(f"Unrecognized metadata row: {line}")
            code, var, label, units = match.groups()
            out.append(f"| {code} | `{var}` | {label} | `{units}` |")
        out.append("")
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in inventories differ")
    args = parser.parse_args()
    outputs = {"namelist-inventory.md": namelists(), "raw-output.md": raw_output(),
               "conversion-metadata.md": conversion_metadata()}
    for name, text in outputs.items():
        path = DOC / "reference" / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Outdated {path.relative_to(ROOT)}; run python3 plasim/doc/generate_reference.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)} source inventories")


if __name__ == "__main__":
    main()
